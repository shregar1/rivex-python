from __future__ import annotations

from enum import IntEnum

from rivex.enums.abstraction import IEnum


class APIStatus(IEnum, IntEnum):
    CONTINUE = 100
    SWITCHING_PROTOCOLS = 101

    OK = 200
    CREATED = 201
    ACCEPTED = 202
    NO_CONTENT = 204

    MOVED_PERMANENTLY = 301
    FOUND = 302
    NOT_MODIFIED = 304
    TEMPORARY_REDIRECT = 307
    PERMANENT_REDIRECT = 308

    BAD_REQUEST = 400
    UNAUTHORIZED = 401
    FORBIDDEN = 403
    NOT_FOUND = 404
    METHOD_NOT_ALLOWED = 405
    CONFLICT = 409
    UNPROCESSABLE_ENTITY = 422
    TOO_MANY_REQUESTS = 429

    INTERNAL_SERVER_ERROR = 500
    BAD_GATEWAY = 502
    SERVICE_UNAVAILABLE = 503
    GATEWAY_TIMEOUT = 504


StatusCode = APIStatus


class APIResult(str, IEnum):
    SUCCESS = "SUCCESS"
    FAILURE = "FAILURE"
    PENDING = "PENDING"


class _StatusCodes:
    HTTP_100_CONTINUE = APIStatus.CONTINUE
    HTTP_101_SWITCHING_PROTOCOLS = APIStatus.SWITCHING_PROTOCOLS

    HTTP_200_OK = APIStatus.OK
    HTTP_201_CREATED = APIStatus.CREATED
    HTTP_202_ACCEPTED = APIStatus.ACCEPTED
    HTTP_204_NO_CONTENT = APIStatus.NO_CONTENT

    HTTP_301_MOVED_PERMANENTLY = APIStatus.MOVED_PERMANENTLY
    HTTP_302_FOUND = APIStatus.FOUND
    HTTP_304_NOT_MODIFIED = APIStatus.NOT_MODIFIED
    HTTP_307_TEMPORARY_REDIRECT = APIStatus.TEMPORARY_REDIRECT
    HTTP_308_PERMANENT_REDIRECT = APIStatus.PERMANENT_REDIRECT

    HTTP_400_BAD_REQUEST = APIStatus.BAD_REQUEST
    HTTP_401_UNAUTHORIZED = APIStatus.UNAUTHORIZED
    HTTP_403_FORBIDDEN = APIStatus.FORBIDDEN
    HTTP_404_NOT_FOUND = APIStatus.NOT_FOUND
    HTTP_405_METHOD_NOT_ALLOWED = APIStatus.METHOD_NOT_ALLOWED
    HTTP_409_CONFLICT = APIStatus.CONFLICT
    HTTP_422_UNPROCESSABLE_ENTITY = APIStatus.UNPROCESSABLE_ENTITY
    HTTP_429_TOO_MANY_REQUESTS = APIStatus.TOO_MANY_REQUESTS

    HTTP_500_INTERNAL_SERVER_ERROR = APIStatus.INTERNAL_SERVER_ERROR
    HTTP_502_BAD_GATEWAY = APIStatus.BAD_GATEWAY
    HTTP_503_SERVICE_UNAVAILABLE = APIStatus.SERVICE_UNAVAILABLE
    HTTP_504_GATEWAY_TIMEOUT = APIStatus.GATEWAY_TIMEOUT


status = _StatusCodes()
